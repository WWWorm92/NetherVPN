//go:build linux

package app

import (
	"context"
	"errors"
	"net"
	"net/netip"

	"github.com/WWWorm92/NetherVPN/internal/session"
	"github.com/WWWorm92/NetherVPN/internal/tun"
	"github.com/WWWorm92/NetherVPN/internal/tunnel"
)

// runPumps shuts down both loops if either returns or context is cancelled.
// It deliberately has no implicit system configuration privileges.
func runPumps(ctx context.Context, device *tun.Device, conn *net.UDPConn, peer *net.UDPAddr, secure *session.Session, mtu int, allowed netip.Addr) error {
	ctx,cancel:=context.WithCancel(ctx)
	defer cancel()
	errCh:=make(chan error,2)
	// Outgoing local packets are generated by the local OS, not by the remote.
	// Their source address cannot be constrained to the remote peer address.
	go func(){errCh<-tunnel.PumpToUDP(ctx,device,conn,peer,secure,mtu,func(p []byte)error{return nil})}()
	go func(){errCh<-tunnel.PumpFromUDP(ctx,device,conn,peer,secure,mtu,func(p []byte)error{return tunnel.VerifySource(p,allowed)})}()
	select {
	case err:=<-errCh:
		cancel()
		_ = device.Close()
		if errors.Is(err,context.Canceled){return nil}
		return err
	case <-ctx.Done():
		cancel()
		_ = device.Close()
		_ = <-errCh
		return nil
	}
}
